import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const [css, js] = await Promise.all([
  readFile(new URL("../frontend/dist/assets/app.css", import.meta.url), "utf8"),
  readFile(new URL("../frontend/dist/assets/app.js", import.meta.url), "utf8"),
]);

// Short content hash appended to asset URLs as a cache-busting version,
// so long-lived browser caches never serve a stale bundle after a deploy.
const version = createHash("sha256").update(css).update(js).digest("hex").slice(0, 12);

const banner = "// Generated by scripts/generate-assets.mjs from frontend/dist — do not edit by hand.\n";
const output = `${banner}export const APP_CSS = ${JSON.stringify(css)};\n\nexport const APP_JS = ${JSON.stringify(js)};\n\nexport const ASSETS_VERSION = ${JSON.stringify(version)};\n`;

await writeFile(new URL("../src/assets.generated.js", import.meta.url), output);
console.log(`Wrote src/assets.generated.js (${css.length} B CSS, ${js.length} B JS, v${version})`);
