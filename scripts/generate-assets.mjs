import { execSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const [css, js] = await Promise.all([
  readFile(new URL("../frontend/dist/assets/app.css", import.meta.url), "utf8"),
  readFile(new URL("../frontend/dist/assets/app.js", import.meta.url), "utf8"),
]);

// Short content hash appended to asset URLs as a cache-busting version,
// so long-lived browser caches never serve a stale bundle after a deploy.
const version = createHash("sha256").update(css).update(js).digest("hex").slice(0, 12);

// Commit the bundle was built from. Shown in the UI and compared against
// /__z/api/version so open tabs reload themselves after a deploy.
function currentCommit() {
  try {
    return execSync("git rev-parse --short HEAD", {
      stdio: ["ignore", "pipe", "ignore"],
    })
      .toString()
      .trim();
  } catch {
    return "unknown";
  }
}
const commit = currentCommit();

const banner = "// Generated by scripts/generate-assets.mjs from frontend/dist — do not edit by hand.\n";
const output = `${banner}export const APP_CSS = ${JSON.stringify(css)};\n\nexport const APP_JS = ${JSON.stringify(js)};\n\nexport const ASSETS_VERSION = ${JSON.stringify(version)};\n\nexport const BUILD_COMMIT = ${JSON.stringify(commit)};\n`;

await writeFile(new URL("../src/assets.generated.js", import.meta.url), output);
console.log(`Wrote src/assets.generated.js (${css.length} B CSS, ${js.length} B JS, v${version}, ${commit})`);
